(function () {
  const X = window.AU_ARCH;
  if (!X) return;
  const { el, svgEl, heading } = X;
  X.add('line-art', function (ctx, k) {
    const d = ctx.data;
    const W = ctx.W, H = ctx.H;
    const night = !!d.night;
    k.root.style.padding = '0';
    const card = el('div', 'la-card' + (night ? ' is-night' : ''), k.root);
    const cw = W * (ctx.portrait ? 0.9 : 0.86), ch = H * (ctx.portrait ? 0.62 : 0.78);
    card.style.width = cw + 'px';
    card.style.height = ch + 'px';
    const svg = svgEl('svg', { viewBox: `0 0 ${cw} ${ch}`, width: cw, height: ch, class: 'la-svg' }, card);
    svg.setAttribute('data-layer', 'drawing');
    const ink = night ? '#E9E4D8' : 'var(--ink)';
    const paper = night ? '#1F2547' : 'var(--bg)';
    const sw = Math.max(2.2, cw / 640);
    const pen = (dd, extra) => svgEl('path', Object.assign({ d: dd, fill: 'none', stroke: ink, 'stroke-width': sw, 'stroke-linecap': 'round', 'stroke-linejoin': 'round' }, extra || {}), svg);
    const base = ch * 0.74;
    const wob = (x0, x1, y, amp, n) => {
      let s = `M${x0},${y}`;
      for (let i = 1; i <= n; i++) {
        const x = x0 + (x1 - x0) * i / n;
        s += ` Q${x - (x1 - x0) / n / 2},${y + (i % 2 ? -amp : amp)} ${x},${y + (i % 3 === 0 ? amp * 0.3 : 0)}`;
      }
      return s;
    };
    const strokes = [];
    strokes.push(pen(wob(cw * 0.02, cw * 0.98, base, ch * 0.012, 9)));
    strokes.push(pen(`M${cw * 0.02},${base - ch * 0.12} C${cw * 0.2},${base - ch * 0.26} ${cw * 0.34},${base - ch * 0.2} ${cw * 0.48},${base - ch * 0.1}`));
    strokes.push(pen(`M${cw * 0.56},${base - ch * 0.06} C${cw * 0.7},${base - ch * 0.22} ${cw * 0.86},${base - ch * 0.24} ${cw * 0.98},${base - ch * 0.12}`));
    const hx = cw * 0.66, hw = cw * 0.14, hh = ch * 0.2;
    strokes.push(pen(`M${hx},${base} L${hx + 2},${base - hh} L${hx + hw - 1},${base - hh - 2} L${hx + hw},${base}`));
    strokes.push(pen(`M${hx - hw * 0.12},${base - hh + 4} L${hx + hw * 0.5},${base - hh - hh * 0.6} L${hx + hw * 1.12},${base - hh + 2}`));
    const win = svgEl('rect', { x: hx + hw * 0.18, y: base - hh * 0.72, width: hw * 0.26, height: hh * 0.28, rx: 3, fill: night ? '#FFCF66' : paper, stroke: ink, 'stroke-width': 2 }, svg);
    strokes.push(pen(`M${hx + hw * 0.62},${base} L${hx + hw * 0.62},${base - hh * 0.5} Q${hx + hw * 0.74},${base - hh * 0.56} ${hx + hw * 0.86},${base - hh * 0.5} L${hx + hw * 0.86},${base}`));
    strokes.push(pen(`M${hx + hw * 0.78},${base - hh - hh * 0.3} L${hx + hw * 0.78},${base - hh - hh * 0.62} L${hx + hw * 0.92},${base - hh - hh * 0.62} L${hx + hw * 0.92},${base - hh - hh * 0.18}`));
    const tx = cw * 0.2;
    strokes.push(pen(`M${tx},${base} C${tx - 3},${base - ch * 0.1} ${tx + 4},${base - ch * 0.16} ${tx},${base - ch * 0.22}`));
    strokes.push(pen(`M${tx - cw * 0.05},${base - ch * 0.22} c0,-${ch * 0.1} ${cw * 0.1},-${ch * 0.12} ${cw * 0.1},0 c${cw * 0.03},${ch * 0.06} -${cw * 0.13},${ch * 0.07} -${cw * 0.1},0 z`, { fill: paper }));
    const lx = cw * 0.42;
    strokes.push(pen(`M${lx},${base} C${lx + 2},${base - ch * 0.2} ${lx - 2},${base - ch * 0.3} ${lx + 1},${base - ch * 0.42} q${cw * 0.03},-4 ${cw * 0.05},4`));
    const lantern = svgEl('g', { class: 'la-lantern' }, svg);
    const pivot = [lx + cw * 0.051, base - ch * 0.415];
    svgEl('path', { d: `M${pivot[0]},${pivot[1]} L${pivot[0]},${pivot[1] + ch * 0.05}`, stroke: ink, 'stroke-width': 2, fill: 'none' }, lantern);
    svgEl('rect', { x: pivot[0] - cw * 0.012, y: pivot[1] + ch * 0.05, width: cw * 0.024, height: ch * 0.05, rx: 4, fill: night ? '#FFCF66' : 'var(--accent)', stroke: ink, 'stroke-width': 2 }, lantern);
    const sun = svgEl('circle', { cx: cw * 0.86, cy: ch * 0.2, r: ch * 0.06, fill: night ? '#E9E4D8' : 'none', stroke: ink, 'stroke-width': 2.4 }, svg);
    strokes.push(sun);
    const smoke = pen(`M${hx + hw * 0.85},${base - hh - hh * 0.66} q-8,-14 4,-26 q10,-12 -2,-26`, { opacity: 0.7 });
    const birds = [0, 1, 2].map((i) => ({ el: svgEl('path', { d: '', fill: 'none', stroke: ink, 'stroke-width': 2, 'stroke-linecap': 'round' }, svg), x: cw * (0.3 + i * 0.06), y: ch * (0.18 + (i % 2) * 0.05), ph: i * 0.7 }));
    const clouds = [0, 1].map((i) => pen(`M${cw * (0.12 + i * 0.4)},${ch * (0.14 + i * 0.06)} q10,-18 30,-8 q14,-14 30,2 q18,0 14,14 z`, { fill: paper }));
    const walker = svgEl('g', { class: 'la-walker' }, svg);
    const sc = (ch / 520) * 1.6;
    const limb = (gEl) => [svgEl('path', { fill: 'none', stroke: ink, 'stroke-width': 2.2, 'stroke-linecap': 'round' }, gEl), svgEl('path', { fill: 'none', stroke: ink, 'stroke-width': 2.2, 'stroke-linecap': 'round' }, gEl)];
    const legs = [limb(walker), limb(walker)];
    const torso = svgEl('path', { fill: paper, stroke: ink, 'stroke-width': 2.2, 'stroke-linejoin': 'round' }, walker);
    const head = svgEl('circle', { r: 9 * sc, fill: paper, stroke: ink, 'stroke-width': 2.2 }, walker);
    const scarf = svgEl('path', { fill: 'none', stroke: 'var(--accent)', 'stroke-width': 4, 'stroke-linecap': 'round' }, walker);
    const twoStroke = (pair, x0, y0, x1, y1, x2, y2, w) => {
      const nx = -(y2 - y0), ny = x2 - x0, len = Math.hypot(nx, ny) || 1;
      const ux = nx / len, uy = ny / len;
      const at = (px, py, s) => `${(px + ux * s).toFixed(1)},${(py + uy * s).toFixed(1)}`;
      pair[0].setAttribute('d', `M${at(x0, y0, w)} Q${at(x1, y1, w)} ${at(x2, y2, w * 0.6)}`);
      pair[1].setAttribute('d', `M${at(x0, y0, -w)} Q${at(x1, y1, -w)} ${at(x2 - (x2 - x1) * 0.15, y2 - (y2 - y1) * 0.15, -w * 0.6)}`);
    };
    const minJerk = (p) => p * p * p * (10 - 15 * p + 6 * p * p);
    const leg = 34 * sc;
    const stride = leg * 0.9;
    const period = 1.05;
    const speed = (stride / (period / 2)) * 0.5;
    ctx.onFrame((t) => {
      const wx = cw * 0.06 + t * speed;
      const groundY = base - 2;
      const ph = (t / period) % 1;
      const footX = (p) => (p < 0.5 ? (minJerk(p * 2) - 0.5) * stride : (0.5 - (p - 0.5) * 2) * stride);
      const lift = (p) => (p < 0.5 ? Math.sin(p * 2 * Math.PI) * leg * 0.14 : 0);
      const f1 = footX(ph), f2 = footX((ph + 0.5) % 1);
      const spread = Math.abs(f1 - f2) / stride;
      const hipY = groundY - leg * 1.05 + spread * leg * 0.06;
      const hipX = wx;
      twoStroke(legs[0], hipX, hipY, hipX + f1 * 0.5, hipY + leg * 0.55, hipX + f1, groundY - lift(ph), 2.6 * sc);
      twoStroke(legs[1], hipX, hipY, hipX + f2 * 0.5, hipY + leg * 0.55, hipX + f2, groundY - lift((ph + 0.5) % 1), 2.6 * sc);
      const tw = 12 * sc, th = leg * 0.95;
      torso.setAttribute('d', `M${hipX - tw * 0.7},${hipY} Q${hipX - tw},${hipY - th * 0.55} ${hipX - tw * 0.4},${hipY - th} L${hipX + tw * 0.5},${hipY - th} Q${hipX + tw},${hipY - th * 0.5} ${hipX + tw * 0.8},${hipY} Z`);
      head.setAttribute('cx', hipX + 2);
      head.setAttribute('cy', hipY - th - 9 * sc - 2);
      const tail = 6 * Math.exp(-0.2 * t) * Math.cos(3.1 * t) + 4;
      scarf.setAttribute('d', `M${hipX - tw * 0.3},${hipY - th + 4} q-${(10 + tail).toFixed(1)},4 -${(22 + tail).toFixed(1)},${(8 + tail * 0.4).toFixed(1)}`);
      const ang = 11 * Math.exp(-0.35 * t) * Math.cos(2.6 * t) + 1.2 * Math.cos(0.9 * t);
      lantern.setAttribute('transform', `rotate(${ang.toFixed(2)} ${pivot[0]} ${pivot[1]})`);
      birds.forEach((b) => {
        const up = Math.floor((t * 3.4 + b.ph) % 2) === 0;
        const x = b.x + t * cw * 0.02, y = b.y + 4 * Math.cos(0.8 * t + b.ph);
        const s = 9 * sc;
        b.el.setAttribute('d', up ? `M${x - s},${y - s * 0.5} Q${x - s * 0.4},${y - s * 0.7} ${x},${y} Q${x + s * 0.4},${y - s * 0.7} ${x + s},${y - s * 0.5}`
          : `M${x - s},${y + s * 0.3} Q${x - s * 0.4},${y - s * 0.2} ${x},${y} Q${x + s * 0.4},${y - s * 0.2} ${x + s},${y + s * 0.3}`);
      });
      clouds.forEach((c, i) => c.setAttribute('transform', `translate(${(t * (6 + i * 4)).toFixed(1)} 0)`));
      smoke.setAttribute('transform', `translate(${(3 * Math.cos(1.4 * t)).toFixed(1)} ${(-((t * 6) % 12)).toFixed(1)})`);
    });
    ctx.draw(strokes, { at: 0.15, duration: 0.7, stagger: 0.12, ease: 'au.glide' });
    ctx.tl.from([win, lantern], { opacity: 0, duration: 0.5 }, 0.15 + strokes.length * 0.12);
    ctx.tl.from(walker, { opacity: 0, duration: 0.5 }, 0.6);
    const headBox = el('div', 'la-head', k.root);
    heading(ctx, k, headBox, { kicker: d.kicker, title: d.title, subtitle: d.subtitle }, { size: 'md', style: 'blur' }).play(0.4);
    ctx.tl.from(card, { y: 40, opacity: 0, duration: 0.8, ease: 'au.softLand' }, 0);
  });
})();
